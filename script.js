let cart = [];

let currentCategory = "all";


/* DISPLAY MENU */

function displayFoods(list = foods) {

    const container =
        document.getElementById("foodContainer");

    container.innerHTML = "";

    list.forEach(food => {

        const card = document.createElement("div");

        card.className = "food-card";

        card.innerHTML = `

            <div class="food-icon">
                ${food.icon}
            </div>

            <span class="category-name">
                ${food.category.toUpperCase()}
            </span>

            <h3>${food.name}</h3>

            <div class="price">
                ₹${food.price}
            </div>

            <div class="quantity">

                <button onclick="changeQuantity(${food.id}, -1)">
                    −
                </button>

                <span id="qty-${food.id}">
                    1
                </span>

                <button onclick="changeQuantity(${food.id}, 1)">
                    +
                </button>

            </div>

            <button
                class="add-btn"
                onclick="addToCart(${food.id})">

                Add to Cart 🛒

            </button>
        `;

        container.appendChild(card);

    });

}


/* QUANTITY */

const quantities = {};


function changeQuantity(id, change) {

    if (!quantities[id]) {

        quantities[id] = 1;

    }

    quantities[id] += change;

    if (quantities[id] < 1) {

        quantities[id] = 1;

    }

    if (quantities[id] > 20) {

        quantities[id] = 20;

    }

    document.getElementById(
        `qty-${id}`
    ).innerText = quantities[id];

}


/* ADD TO CART */

function addToCart(id) {

    const food =
        foods.find(item => item.id === id);

    const qty =
        quantities[id] || 1;

    const existing =
        cart.find(item => item.id === id);

    if (existing) {

        existing.quantity += qty;

        if (existing.quantity > 20) {

            existing.quantity = 20;

        }

    } else {

        cart.push({

            ...food,

            quantity: qty

        });

    }

    updateCart();

    showToast(`${food.name} added to cart`);

}


/* UPDATE CART */

function updateCart() {

    const count =
        cart.reduce(
            (sum,item) =>
            sum + item.quantity,
            0
        );

    document.getElementById(
        "cartCount"
    ).innerText = count;

    renderCart();

}


/* RENDER CART */

function renderCart() {

    const container =
        document.getElementById("cartItems");

    container.innerHTML = "";

    let total = 0;

    cart.forEach(item => {

        total +=
            item.price * item.quantity;

        const div =
            document.createElement("div");

        div.className = "cart-item";

        div.innerHTML = `

            <div>

                <strong>
                    ${item.icon}
                    ${item.name}
                </strong>

                <br>

                ₹${item.price}
                ×
                ${item.quantity}

            </div>

            <button
                onclick="removeFromCart(${item.id})">

                ❌

            </button>

        `;

        container.appendChild(div);

    });

    document.getElementById(
        "cartTotal"
    ).innerText = total;

}


/* REMOVE */

function removeFromCart(id) {

    cart =
        cart.filter(
            item => item.id !== id
        );

    updateCart();

}


/* OPEN CART */

function openCart() {

    document.getElementById(
        "cartOverlay"
    ).style.display = "flex";

}


/* CLOSE CART */

function closeCart() {

    document.getElementById(
        "cartOverlay"
    ).style.display = "none";

}


/* FILTER */

function filterMenu(category) {

    currentCategory = category;

    if (category === "all") {

        displayFoods(foods);

        return;

    }

    const filtered =
        foods.filter(
            food =>
            food.category === category
        );

    displayFoods(filtered);

}


/* SEARCH */

function searchFood() {

    const text =
        document.getElementById(
            "searchInput"
        ).value.toLowerCase();

    let result =
        foods.filter(food => {

            const matchesText =
                food.name
                .toLowerCase()
                .includes(text);

            const matchesCategory =
                currentCategory === "all" ||
                food.category === currentCategory;

            return matchesText &&
                   matchesCategory;

        });

    displayFoods(result);

}


/* ORDER */

function placeOrder() {

    if (cart.length === 0) {

        alert(
            "Please add items to cart first."
        );

        return;

    }

    const orderId =
        "SVCE" +
        Math.floor(
            10000 + Math.random() * 90000
        );

    alert(
        `Order placed successfully!\n\n` +
        `Order ID: ${orderId}\n\n` +
        `Please collect your order from SVCE Canteen.`
    );

    cart = [];

    updateCart();

    closeCart();

}


